const C = (f) => (f - 0.5) * 2.6 // fractional → centred world coords

const corners = () => {
  const out = []
  for (let x = 0; x <= 1; x++)
    for (let y = 0; y <= 1; y++)
      for (let z = 0; z <= 1; z++) out.push([x, y, z])
  return out
}

const faceCenters = () => [
  [0.5, 0.5, 0],
  [0.5, 0.5, 1],
  [0.5, 0, 0.5],
  [0.5, 1, 0.5],
  [0, 0.5, 0.5],
  [1, 0.5, 0.5],
]

const edgeCenters = () => {
  const out = []
  for (let i = 0; i <= 1; i++)
    for (let j = 0; j <= 1; j++) {
      out.push([0.5, i, j])
      out.push([i, 0.5, j])
      out.push([i, j, 0.5])
    }
  return out
}

const mapAtoms = (list, el, r) => list.map(([x, y, z]) => ({ el, pos: [C(x), C(y), C(z)], r }))

// පරමාණු අතර දුර මත පදනම්ව සහසංයුජ බන්ධන සොයාගැනීම
function autoBonds(atoms, factor = 1.12) {
  const bonds = []
  let min = Infinity
  for (let i = 0; i < atoms.length; i++)
    for (let j = i + 1; j < atoms.length; j++) {
      const d = Math.hypot(
        atoms[i].pos[0] - atoms[j].pos[0],
        atoms[i].pos[1] - atoms[j].pos[1],
        atoms[i].pos[2] - atoms[j].pos[2]
      )
      if (d > 0.01 && d < min) min = d
    }
  for (let i = 0; i < atoms.length; i++)
    for (let j = i + 1; j < atoms.length; j++) {
      const d = Math.hypot(
        atoms[i].pos[0] - atoms[j].pos[0],
        atoms[i].pos[1] - atoms[j].pos[1],
        atoms[i].pos[2] - atoms[j].pos[2]
      )
      if (d <= min * factor) bonds.push([i, j])
    }
  return bonds
}

// --- විෂම ලෝහ දැලිස (graphite) ---
function graphiteAtoms() {
  const a = 1.42
  const d = a * Math.sqrt(3)
  const a1 = [d, 0]
  const a2 = [d / 2, (d * Math.sqrt(3)) / 2]
  const s = 0.62
  const atoms = []
  for (let l = 0; l < 2; l++) {
    const y = (l === 0 ? -1 : 1) * 0.85
    for (let i = -1; i <= 1; i++)
      for (let j = -1; j <= 1; j++) {
        const ox = i * a1[0] + j * a2[0]
        const oz = i * a1[1] + j * a2[1]
        atoms.push({ el: 'C', pos: [(ox) * s, y, oz * s], r: 0.17, layer: l })
        atoms.push({ el: 'C', pos: [(ox + a) * s, y, oz * s], r: 0.17, layer: l })
      }
  }
  // තලය තුළ බන්ධන
  const bonds = []
  for (let i = 0; i < atoms.length; i++)
    for (let j = i + 1; j < atoms.length; j++) {
      if (atoms[i].layer !== atoms[j].layer) continue
      const dd = Math.hypot(
        atoms[i].pos[0] - atoms[j].pos[0],
        atoms[i].pos[2] - atoms[j].pos[2]
      )
      if (dd < 1.5 * 0.62 * 1.1) bonds.push([i, j])
    }
  return { atoms, bonds }
}

