function safeOptions(correct, pool, count = 4) {
  const opts = [correct]
  for (const p of pool) {
    if (opts.length >= count) break
    if (!opts.includes(p)) opts.push(p)
  }
  // නිවැරදි පිළිතුර නිතරම මුල් නොවන ලෙස මිශ්‍ර කරන්න (ස්ථාවර seed)
  const seed = correct.length + opts.length
  const rotated = [...opts.slice(seed % opts.length), ...opts.slice(0, seed % opts.length)]
  return { options: rotated, correct: rotated.indexOf(correct) }
}

