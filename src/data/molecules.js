// --- CH4 ---------------------------------------------------------------
const t = 1.05
const ch4H = [
  [t, t, t],
  [t, -t, -t],
  [-t, t, -t],
  [-t, -t, t],
].map((v) => v.map((x) => +(x * 1.15).toFixed(3)))

// --- NH3 (H–N–H = 107°) ----------------------------------------------
const nh3H = ring(3, 1.58, 0).map(([x, , z]) => [
  +(x * 0.928).toFixed(3),
  -0.63,
  +(z * 0.928).toFixed(3),
])

// --- H2O (H–O–H = 104.5°) --------------------------------------------
