// Bond lengths are visual-scale approximations (Å × ~1.0) for the 3D viewer.

const rad = (d) => (d * Math.PI) / 180
const ring = (n, r, y = 0, phase = 0) =>
  Array.from({ length: n }, (_, i) => {
    const a = phase + (2 * Math.PI * i) / n
    return [+(r * Math.cos(a)).toFixed(3), y, +(r * Math.sin(a)).toFixed(3)]
  })

