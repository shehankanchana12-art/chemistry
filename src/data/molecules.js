const h2oH = [
  +(1.5 * Math.sin(hoh)).toFixed(3),
  +(1.5 * Math.cos(hoh)).toFixed(3),
  0,
]
const h2oH2 = [-h2oH[0], h2oH[1], 0]

const bcl3 = ring(3, 2.0, 0)

